const root = document.documentElement;
const texts = document.querySelectorAll("[data-i18n]");
const langButtons = document.querySelectorAll("[data-lang]");
const titles = { en: document.title, vi: root.dataset.titleVi || document.title };

function setLang(lang) {
  for (const el of texts) {
    el.dataset.en ??= el.innerHTML;
    el.innerHTML = lang === "vi" ? VI[el.dataset.i18n] ?? el.dataset.en : el.dataset.en;
  }
  root.lang = lang;
  document.title = titles[lang];
  for (const b of langButtons) b.setAttribute("aria-pressed", String(b.dataset.lang === lang));
  try { localStorage.setItem("ztabs-lang", lang); } catch {}
}

for (const b of langButtons) b.addEventListener("click", () => setLang(b.dataset.lang));

// ?lang=vi makes a shareable Vietnamese link; otherwise the last choice wins, English by default.
let saved = new URLSearchParams(location.search).get("lang");
if (!saved) try { saved = localStorage.getItem("ztabs-lang"); } catch {}
if (saved === "vi") setLang("vi");

const sw = document.getElementById("switch");
sw?.addEventListener("click", () => {
  const on = sw.getAttribute("aria-checked") !== "true";
  sw.setAttribute("aria-checked", String(on));
  const demo = sw.closest(".demo");
  demo.classList.toggle("is-off", !on);
  demo.classList.add("touched");
});
